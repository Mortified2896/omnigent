def test_record_request_retries_on_collision(state_root: Path) -> None:
    """``record_request`` retries a fresh id when the first collides."""
    store = UpdaterStore(state_root=state_root)
    payload = _payload()
    # Pre-create a request file so the next id collides with the
    # first id generated by record_request.
    from omnigent.updater.protocol import (
        Authorization,
        RequestRecord,
        new_request_id,
    )

    collision_id = new_request_id()
    record = RequestRecord(
        request_id=collision_id,
        target_sha="0" * 40,
        expected_current_sha="0" * 40,
        origin_session_id=None,
        origin_conversation_id=None,
        requested_by="operator:tester",
        created_at="2026-01-01T00:00:00Z",
        authorization=Authorization(kind="operator", operator="tester"),
    )
    store.create_request(record)
    # Patch the id generator temporarily so the first attempt
    # collides. After the retry succeeds, the new id is on disk.
    import omnigent.updater.request_tool as rt

    real = rt.new_request_id
    calls = {"n": 0}

    def fake() -> str:
        calls["n"] += 1
        if calls["n"] == 1:
            return collision_id
        return real()

    rt.new_request_id = fake  # type: ignore[assignment]
    try:
        outcome = record_request(payload)
    finally:
        rt.new_request_id = real  # type: ignore[assignment]
    assert outcome.request_id != collision_id


def test_sys_update_request_payload_is_narrow() -> None:
    """The ``sys_update_request`` adapter only produces the narrow schema."""
    payload = sys_update_request_payload(
        target_sha="0" * 40,
        expected_current_sha="0" * 40,
        origin_conversation_id="conv_abc",
    )
    assert set(payload.keys()) == {
        "target_sha",
        "expected_current_sha",
        "requested_by",
        "authorization",
        "origin_conversation_id",
    }
    assert payload["requested_by"] == "verity"
    assert payload["authorization"] == {"kind": "verity"}


def test_invoke_sys_update_request_returns_request_id(state_root: Path) -> None:
    result = invoke_sys_update_request(
        target_sha="0" * 40,
        expected_current_sha="0" * 40,
        origin_conversation_id="conv_abc",
    )
    assert result["request_id"]
    assert result["request_path"].endswith(f"{result['request_id']}.json")
    on_disk = layout.requests_dir() / f"{result['request_id']}.json"
    assert on_disk.is_file()
