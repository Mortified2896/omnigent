def test_record_request_accepts_verity_kind(state_root: Path) -> None:
    """``verity``-kind requests do not require an operator name."""
    payload = _payload()
    payload["requested_by"] = "verity"
    payload["authorization"] = {"kind": "verity"}
    outcome = record_request(payload)
    assert outcome.request_id


