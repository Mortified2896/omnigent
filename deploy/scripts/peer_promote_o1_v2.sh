sha256() { sha256sum "$1" | awk '{print $1}'; }

# service_state_active <unit>
# Returns 0 iff the unit is in the "active" state. Uses the
# vetted peer-deployer helper to avoid the broken
# `is-active | grep -q` pattern under pipefail.
service_state_active() {
  local unit="$1"
  local state
  state="$(systemctl is-active "$unit" 2>/dev/null || true)"
  state="${state,,}"
  state="${state//[[:space:]]/}"
  [[ "$state" == "active" ]]
}

