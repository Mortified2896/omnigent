# tx_write_json <python-expression-on-tx_dir-and-tx_id>
# Runs an inline Python snippet that mutates the transaction record.
# The snippet receives ``tx_dir`` and ``tx_id`` in scope.
tx_write_json() {
  local expr="$1"
  SYSTEM_PYTHON="$SYSTEM_PYTHON" python3 -c "
import json, os
p = '${TX_DIR}/transaction.json'
d = json.load(open(p))
${expr}
json.dump(d, open(p, 'w'), indent=2, sort_keys=True)
"
  cp "${TX_DIR}/transaction.json" "${EVIDENCE_DIR}/tx-${TX_ID}/transaction.json"
}

update_tx_phase() {
  tx_write_json "d['phase'] = '$1'"
}

mark_mutation_boundary() {
  tx_write_json "d['mutation_boundary_crossed'] = True"
}

backup_target_db() {
  log "backing up target DB"
  install -d "${DB_BACKUP_DIR}"
  if [[ ! -f "$TARGET_DB" ]]; then
    fail "target DB missing: $TARGET_DB"
  fi
  if ! sqlite3 "$TARGET_DB" "PRAGMA integrity_check;" | grep -q "^ok$"; then
    fail "target DB integrity check failed BEFORE backup"
  fi
  python3 -c "
import sqlite3
src = sqlite3.connect('${TARGET_DB}')
dst = sqlite3.connect('${DB_BACKUP_PATH}')
with dst:
    src.backup(dst)
dst.close()
src.close()
"
  if ! sqlite3 "$DB_BACKUP_PATH" "PRAGMA integrity_check;" | grep -q "^ok$"; then
    fail "DB backup integrity check failed"
  fi
  local backup_sha
  backup_sha="$(sha256 "$DB_BACKUP_PATH")"
  tx_write_json "
d['db_backup_sha256'] = '${backup_sha}'
d['db_backup_integrity'] = 'ok'
"
  log "DB backup: $DB_BACKUP_PATH ($backup_sha)"
}

# stage_candidate_runtime
#
# The new, deterministic staging phase. Delegates entirely to the
# peer_deployer.staging module via the ``stage`` CLI subcommand.
# This means:
#
#   * supervisor's site-packages is copied wholesale
#   * the three SDK wheels are installed with --no-deps
#   * the candidate's runtime identity is verified (SHA + version)
#   * the candidate's package versions match the supervisor closure
#   * PROVENANCE.txt and artifacts/ are written
#   * .complete is touched only after every verify step passes
#
# Live PyPI is never consulted.
stage_candidate_runtime() {
  log "staging candidate runtime at $STAGING_ROOT (per-tx)"
  install -d "${EVIDENCE_DIR}/tx-${TX_ID}"
  cd /tmp
  SYSTEM_PYTHON="$SYSTEM_PYTHON" python3 "${PEER_DEPLOYER_RUNNER}" \
    --target "$TARGET" \
    --supervisor "$SUPERVISOR" \
    --tx-id "$TX_ID" \
    stage \
    2>&1 | tee -a "${EVIDENCE_DIR}/tx-${TX_ID}/staging.log"
}

# verify_candidate_runtime_staged_and_verified
#
# Mandatory pre-mutation gate. Verifies:
#   * .complete marker exists in the staging root
#   * PROVENANCE.txt has the canonical schema
#   * the three SDK wheels are present in artifacts/
#   * the candidate's runtime identity matches the accepted artifact
#   * the candidate's package versions match the supervisor closure
#   * omnigent, omnigent_client, omnigent_ui_sdk import cleanly
#
# Implemented as a Python probe so the assertions match the rest of
# the peer_deployer contract.
verify_candidate_runtime_staged_and_verified() {
  log "verifying candidate runtime at $STAGING_ROOT"
  cd /tmp
  local out
  out="$(SYSTEM_PYTHON="$SYSTEM_PYTHON" python3 - <<PY
import json, os, sys, shutil, subprocess
from pathlib import Path

staging_root = Path("${STAGING_ROOT}")
failures = []
if not staging_root.exists():
    failures.append("missing:staging-root")

# Check .complete
if not (staging_root / ".complete").is_file():
    failures.append("missing:.complete")

# Check PROVENANCE
prov = staging_root / "PROVENANCE.txt"
if not prov.is_file():
    failures.append("missing:PROVENANCE.txt")
else:
    text = prov.read_text()
    for required in ("schema_version=", "sha=", "package_version="):
        if required not in text:
            failures.append(f"missing-in-provenance:{required.rstrip('=')}")

# Check artifacts
artifacts = staging_root / "artifacts"
if not artifacts.is_dir():
    failures.append("missing:artifacts/")
for prefix in ("omnigent-", "omnigent_client-", "omnigent_ui_sdk-"):
    if not any(artifacts.glob(f"{prefix}*.whl")):
        failures.append(f"missing-wheel:{prefix}")

# Check runtime identity via import (not regex)
candidate_python = staging_root / "venv" / "bin" / "python"
if not candidate_python.is_file():
    failures.append("missing-python:venv/bin/python")
else:
    probe = subprocess.run(
        [str(candidate_python), "-c",
         "import json; from omnigent._build_info import COMMIT_SHA;"
         "from importlib.metadata import version as v;"
         "json.dump({'commit_sha': COMMIT_SHA, 'version': v('omnigent')}, __import__('sys').stdout)"],
        capture_output=True, text=True, check=False,
        cwd="/tmp",
        env={"PATH": "/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin",
             "PYTHONPATH": "", "PYTHONNOUSERSITE": "1"},
    )
    if probe.returncode != 0:
        failures.append(f"runtime-identity-probe-failed: {probe.stderr.strip()[:200]}")
    else:
        try:
            blob = json.loads(probe.stdout)
        except json.JSONDecodeError:
            failures.append("runtime-identity-probe-not-json")
        else:
            if blob.get("commit_sha") != "${ACCEPTED_SHA}":
                failures.append(f"runtime-sha-mismatch: got {blob.get('commit_sha')!r}")
            if blob.get("version") != "${ACCEPTED_VERSION}":
                failures.append(f"runtime-version-mismatch: got {blob.get('version')!r}")

    # Check that critical imports work
    import_check = subprocess.run(
        [str(candidate_python), "-c",
         "import omnigent, omnigent_client, omnigent_ui_sdk;"
         "import omnigent.db;"
         "import fastapi, opentelemetry;"
         "import opentelemetry.instrumentation.fastapi"],
        capture_output=True, text=True, check=False,
        cwd="/tmp",
        env={"PATH": "/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin",
             "PYTHONPATH": "", "PYTHONNOUSERSITE": "1"},
    )
    if import_check.returncode != 0:
        failures.append(f"import-check-failed: {import_check.stderr.strip()[:300]}")

print(json.dumps({"staging_root": str(staging_root), "failures": failures}))
PY
)"
  echo "$out" | tee -a "${EVIDENCE_DIR}/tx-${TX_ID}/candidate-verification.log"
  local failures
  failures="$(echo "$out" | python3 -c 'import json, sys; d=json.loads(sys.stdin.read()); print(",".join(d["failures"]) if d["failures"] else "")')"
  if [[ -n "$failures" ]]; then
    fail "candidate verification failed: $failures"
  fi
  log "candidate runtime verified"
}

migrate_target_db() {
  log "running target DB migration"
  cd /tmp
  PATH="/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin" \
    "${STAGING_ROOT}/venv/bin/python" -m \
    omnigent.db.migrate --database-url "sqlite:///${TARGET_DB}" 2>&1 | tee -a "${EVIDENCE_DIR}/tx-${TX_ID}/migration.log"
  local new_schema
  new_schema="$(sqlite3 "$TARGET_DB" "SELECT version_num FROM alembic_version;")"
  if [[ "$new_schema" != "$EXPECTED_DB_SCHEMA" ]]; then
    fail "DB migration did not reach expected schema: $new_schema != $EXPECTED_DB_SCHEMA"
  fi
  log "DB migration complete: $new_schema"
}

switch_target_runtime() {
  log "switching target runtime"
  local target_venv="${TARGET_DEPLOY_ROOT}/venv"
  if [[ -L "$target_venv" ]]; then
    local prev_target
    prev_target="$(readlink -f "$target_venv")"
    log "previous runtime was a symlink -> $prev_target"
  elif [[ -d "$target_venv" ]]; then
    # We're promoting to a new release — the existing venv is from
    # the OLD runtime and must be preserved as the rollback target.
    local legacy
    legacy="${TARGET_DEPLOY_ROOT}/venv.legacy-$(date -u +%Y%m%dT%H%M%SZ)"
    log "renaming existing venv to $legacy"
    mv "$target_venv" "$legacy"
    tx_write_json "
if '$legacy' not in d['owned_resources']:
    d['owned_resources'].append('$legacy')
"
  elif [[ -e "$target_venv" ]]; then
    fail "$target_venv is neither a directory nor a symlink"
  fi
  # Atomically swap: move STAGING_ROOT's venv into FINAL_RELEASE,
  # then symlink venv -> FINAL_RELEASE/venv.
  if [[ -e "$FINAL_RELEASE" ]]; then
    fail "final release path already exists: $FINAL_RELEASE"
  fi
  mv "$STAGING_ROOT" "$FINAL_RELEASE"
  rm -f "$STAGING_ROOT"  # safety: shouldn't exist after mv
  local tmp_link="${TARGET_DEPLOY_ROOT}/.venv.tmp"
  ln -sfn "${FINAL_RELEASE}/venv" "$tmp_link"
  mv -T "$tmp_link" "$target_venv"
  log "venv symlink now -> ${FINAL_RELEASE}/venv"
}

write_target_provenance() {
  cp "${FINAL_RELEASE}/PROVENANCE.txt" "${TARGET_DEPLOY_ROOT}/PROVENANCE.txt"
  printf '%s\n' "$ACCEPTED_SHA" > "${TARGET_DEPLOY_ROOT}/DEPLOYED_SHA"
}

start_target_services() {
  log "starting target services"
  systemctl restart "$TARGET_SERVER_UNIT"
  local deadline=$(( $(date +%s) + 90 ))
  while (( $(date +%s) < deadline )); do
    if curl -fsS --max-time 3 "$TARGET_HEALTH_URL" >/dev/null 2>&1; then
      log "target server healthy"
      break
    fi
    sleep 1
  done
  if ! curl -fsS --max-time 3 "$TARGET_HEALTH_URL" >/dev/null 2>&1; then
    fail "target server not healthy after restart"
  fi
  systemctl restart "$TARGET_HOST_UNIT"
  log "target host restarted"
}

verify_target_acceptance() {
  log "verifying target acceptance"
  local info schema
  info="$(curl -fsS --max-time 10 "http://127.0.0.1:4097/v1/info")"
  schema="$(sqlite3 "$TARGET_DB" "SELECT version_num FROM alembic_version;")"
  local actual_version
  actual_version="$(echo "$info" | python3 -c 'import json, sys; print(json.loads(sys.stdin.read())["server_version"])')"
  if [[ "$actual_version" != "$ACCEPTED_VERSION" ]]; then
    fail "target /v1/info server_version mismatch: $actual_version != $ACCEPTED_VERSION"
  fi
  if [[ "$schema" != "$EXPECTED_DB_SCHEMA" ]]; then
    fail "target DB schema mismatch: $schema"
  fi
  log "target acceptance verified: $ACCEPTED_VERSION / $schema"
}

commit_transaction() {
  update_tx_phase "tx_committed"
  log "transaction committed"
}

pause_target_services() {
  log "stopping target services (for rollback)"
  systemctl stop "$TARGET_HOST_UNIT" || true
  systemctl stop "$TARGET_SERVER_UNIT" || true
  sleep 2
}

paired_rollback() {
  local reason="$1"
  log "PAIRED ROLLBACK initiated: $reason"
  tx_write_json "
d['rollback_reason'] = '''$reason'''
d['phase'] = 'rolled_back'
d['rollback_completed'] = True
"

  pause_target_services

  # 1. Restore DB.
  if [[ -f "$DB_BACKUP_PATH" ]] && sqlite3 "$DB_BACKUP_PATH" "PRAGMA integrity_check;" | grep -q "^ok$"; then
    cp "$DB_BACKUP_PATH" "$TARGET_DB"
    chown hermes:hermes "$TARGET_DB"
    chmod 0644 "$TARGET_DB"
    log "DB restored from backup"
  fi

  # 2. Restore old runtime symlink.
  local legacy
  legacy="$(ls -d "${TARGET_DEPLOY_ROOT}/venv.legacy-"* 2>/dev/null | head -1)"
  if [[ -n "$legacy" ]]; then
    rm -f "${TARGET_DEPLOY_ROOT}/venv"
    ln -sfn "$legacy" "${TARGET_DEPLOY_ROOT}/.venv.tmp.rollback"
    mv -T "${TARGET_DEPLOY_ROOT}/.venv.tmp.rollback" "${TARGET_DEPLOY_ROOT}/venv"
    log "runtime symlink restored to $legacy"
  else
    log "no legacy venv found; runtime dir left untouched"
  fi

  # 3. Restore PROVENANCE.txt.
  if [[ -f "$TARGET_DEPLOY_ROOT/venv/PROVENANCE.txt" ]]; then
    cp "$TARGET_DEPLOY_ROOT/venv/PROVENANCE.txt" "$TARGET_DEPLOY_ROOT/PROVENANCE.txt"
  fi

  # 4. Restart target services.
  systemctl restart "$TARGET_SERVER_UNIT"
  systemctl restart "$TARGET_HOST_UNIT"
  log "paired rollback complete"
}

