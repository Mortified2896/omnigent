#!/usr/bin/env bash
# Peer-supervised O1 promotion — host-level deployer v2.
#
# v2 differs from peer_promote_o1.sh in three critical ways, all
# addressing the 2026-08-08 O1 promotion incident:
#
#   1. STAGING IS DETERMINISTIC.
#      The previous script ran ``pip install omnigent[all]`` against
#      live PyPI and let ``pip`` resolve the dependency closure.
#      That failed on ``opentelemetry-instrumentation-fastapi<1,>=0``
#      because the only available releases are 0.x beta. The new
#      script delegates staging to the peer_deployer.staging module,
#      which COPIES the supervisor's site-packages wholesale and
#      installs only the three SDK wheels with ``--no-deps``. Live
#      PyPI is never consulted for any dependency.
#
#   2. STAGING IS PER-TRANSACTION.
#      The previous script staged into
#      ``/opt/omnigent/releases/<sha>`` (the final shared path). Two
#      transactions targeting the same SHA could collide on partial
#      state, and a failed staging left stale partial files at the
#      final location. The new script stages into
#      ``/opt/omnigent/staging/<TX_ID>/`` and only atomically swaps
#      into the final path after every verify step passes.
#
#   3. STAGED-RUNTIME VERIFICATION IS MANDATORY.
#      The previous script crossed the mutation boundary as soon as
#      ``pip install`` returned 0. The new script requires a complete
#      staged runtime to pass ``candidate_runtime_staged_and_verified``
#      BEFORE the transaction is allowed to cross into stop/migrate/
#      switch. If staging fails for any reason, the active O1 runtime,
#      DB, and services are not touched and the rollback subsystem
#      never runs against the active runtime.
#
# The script is intentionally narrow. It cannot upgrade the
# supervisor. It cannot change target/supervisor identity. It cannot
# deploy any artifact other than the exact accepted one. It does not
# weaken the supervisor's sandbox.
#
# This script must be executed by a host-level operator (root) OUTSIDE
# the O2 hermes sandbox. O2 prepares and verifies the command; the
# host-level operator runs it.

set -euo pipefail

