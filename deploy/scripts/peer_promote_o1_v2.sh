assert_supervisor_health() {
  install -d "${EVIDENCE_DIR}"
  install -d "${TX_DIR}"
  log "verifying supervisor health"
  if ! systemctl cat "$SUPERVISOR_SERVER_UNIT" >/dev/null 2>&1; then
    fail "supervisor service unit not installed: $SUPERVISOR_SERVER_UNIT"
  fi
  if ! systemctl cat "$SUPERVISOR_HOST_UNIT" >/dev/null 2>&1; then
    fail "supervisor host unit not installed: $SUPERVISOR_HOST_UNIT"
  fi
  if ! service_state_active "$SUPERVISOR_SERVER_UNIT"; then
    fail "supervisor server is not active: $SUPERVISOR_SERVER_UNIT"
  fi
  if ! service_state_active "$SUPERVISOR_HOST_UNIT"; then
    fail "supervisor host is not active: $SUPERVISOR_HOST_UNIT"
  fi
  if ! curl -fsS --max-time 5 "$SUPERVISOR_HEALTH_URL" >/dev/null 2>&1; then
    fail "supervisor /health not OK: $SUPERVISOR_HEALTH_URL"
  fi
}

assert_supervisor_identity() {
  # Use the import-based helper from peer_deployer.identity so the
  # source form of _build_info.py is irrelevant. This is the fix
  # ported from the manual patch that was applied to peer_promote_o1.sh.
  local actual_sha actual_version
  actual_sha="$(cd /tmp && PYTHONPATH= "${SUPERVISOR_DEPLOY_ROOT}/current/venv/bin/python" -c 'from omnigent._build_info import COMMIT_SHA; print(COMMIT_SHA)')"
  if [[ "$actual_sha" != "$ACCEPTED_SHA" ]]; then
    fail "supervisor installed SHA $actual_sha != accepted $ACCEPTED_SHA"
  fi
  # Read the supervisor's installed version via importlib.metadata
  # (canonical distribution identity). The supervisor's runtime
  # provides this; no source-tree parsing.
  actual_version="$(cd /tmp && PYTHONPATH= "${SUPERVISOR_DEPLOY_ROOT}/current/venv/bin/python" -c 'from importlib.metadata import version; print(version("omnigent"))')"
  if [[ "$actual_version" != "$ACCEPTED_VERSION" ]]; then
    fail "supervisor installed version $actual_version != accepted $ACCEPTED_VERSION"
  fi
  log "supervisor identity verified: $actual_sha / $actual_version"
}

assert_artifact_hashes() {
  if [[ ! -d "$SOURCE_RELEASE" ]]; then
    fail "accepted release dir missing: $SOURCE_RELEASE"
  fi
  if [[ ! -f "$SOURCE_MAIN_WHEEL" ]]; then
    fail "accepted main wheel missing: $SOURCE_MAIN_WHEEL"
  fi
  if [[ ! -f "$SOURCE_SDK_CLIENT_WHEEL" ]]; then
    fail "accepted SDK client wheel missing: $SOURCE_SDK_CLIENT_WHEEL"
  fi
  if [[ ! -f "$SOURCE_SDK_UI_WHEEL" ]]; then
    fail "accepted SDK UI wheel missing: $SOURCE_SDK_UI_WHEEL"
  fi
  local actual
  actual="$(sha256 "$SOURCE_MAIN_WHEEL")"
  [[ "$actual" == "$EXPECTED_MAIN_WHEEL_SHA256" ]] || fail "main wheel SHA mismatch: $actual"
  actual="$(sha256 "$SOURCE_SDK_CLIENT_WHEEL")"
  [[ "$actual" == "$EXPECTED_SDK_CLIENT_WHEEL_SHA256" ]] || fail "SDK client wheel SHA mismatch: $actual"
  actual="$(sha256 "$SOURCE_SDK_UI_WHEEL")"
  [[ "$actual" == "$EXPECTED_SDK_UI_WHEEL_SHA256" ]] || fail "SDK UI wheel SHA mismatch: $actual"
  log "all three wheel SHA-256 verified"
}

